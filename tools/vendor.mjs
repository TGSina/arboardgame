// Copies pinned third-party files from node_modules into lib/ (lib/ is committed; GitHub Pages serves it).
// Usage: npm install && npm run vendor
import { cpSync, mkdirSync, rmSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const nm = (p) => join('node_modules', p);
const need = (p) => {
  if (!existsSync(p)) {
    console.error(`Missing ${p}. Run "npm install" first.`);
    process.exit(1);
  }
  return p;
};
const version = (pkg) => JSON.parse(readFileSync(nm(`${pkg}/package.json`), 'utf8')).version;

// three.js (module build + the AR button addon)
rmSync('lib/three', { recursive: true, force: true });
mkdirSync('lib/three/addons/webxr', { recursive: true });
cpSync(need(nm('three/build')), 'lib/three/build', { recursive: true });
cpSync(need(nm('three/examples/jsm/webxr/ARButton.js')), 'lib/three/addons/webxr/ARButton.js');
cpSync(need(nm('three/LICENSE')), 'lib/three/LICENSE');

// chess.js (single-file ESM build)
rmSync('lib/chess.js', { recursive: true, force: true });
mkdirSync('lib/chess.js', { recursive: true });
cpSync(need(nm('chess.js/dist/esm/chess.js')), 'lib/chess.js/chess.js');
cpSync(need(nm('chess.js/LICENSE')), 'lib/chess.js/LICENSE');

writeFileSync(
  'lib/README.md',
  `# Vendored libraries (generated by tools/vendor.mjs, do not edit by hand)

| Library | Version | Source | License |
|---|---|---|---|
| three.js | ${version('three')} | https://github.com/mrdoob/three.js | MIT (lib/three/LICENSE) |
| chess.js | ${version('chess.js')} | https://github.com/jhlywa/chess.js | BSD-2-Clause (lib/chess.js/LICENSE) |
`
);

console.log(`vendored: three ${version('three')}, chess.js ${version('chess.js')}`);
